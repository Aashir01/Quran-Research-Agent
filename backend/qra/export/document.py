"""The export document model.

One structure that every exporter renders, so a finding looks the same in Word,
in a deck and on paper, and so the things that must not be lost — citations,
provenance tags, the chance baseline next to a count — are carried structurally
rather than re-derived by each format.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import UTC, datetime
from typing import Literal

from sqlalchemy import select
from sqlalchemy.orm import Session

from qra.export.citations import Bibliography, collect, licence_notice
from qra.models import Finding, Hypothesis, HypothesisRun, Note, ResearchRun

BlockKind = Literal["heading", "text", "ayah", "translation", "quote", "stat", "list", "table", "note"]
Provenance = Literal["retrieved", "system_suggested", "own_note"]


@dataclass
class Block:
    kind: BlockKind
    text: str = ""
    # Every block declares where it came from. The three states are visually
    # distinct in every output format, not just on screen.
    provenance: Provenance = "retrieved"
    ref: str | None = None
    language: str = "en"
    rtl: bool = False
    level: int = 2
    items: list[str] = field(default_factory=list)
    rows: list[list[str]] = field(default_factory=list)
    citation: dict | None = None
    meta: dict = field(default_factory=dict)


@dataclass
class Document:
    title: str
    subtitle: str = ""
    language: str = "en"
    blocks: list[Block] = field(default_factory=list)
    citations: list[dict] = field(default_factory=list)
    licence: str = ""
    generated_at: str = field(default_factory=lambda: datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC"))

    @property
    def rtl(self) -> bool:
        return self.language in ("ur", "ar")

    def bibliography(self) -> Bibliography:
        return collect(self.citations, language=self.language)

    def add(self, block: Block) -> None:
        self.blocks.append(block)


