def from_research_run(session: Session, run_id: str, *, language: str | None = None) -> Document:
    """Render an agent run: the Critic's report first, then the draft."""
    run = session.get(ResearchRun, run_id)
    if run is None:
        raise ValueError(f"run {run_id} not found")
    ledger = run.ledger or {}
    language = language or run.language
    strings = _strings(language)

    document = Document(title=run.question, subtitle=f"run {run.id}", language=language)
    rtl = language in ("ur", "ar")

    critic = ledger.get("critic_report") or {}
    if critic:
        document.add(Block(kind="heading", text=f"Critic: {critic.get('verdict', '—')}", level=2))
        document.add(
            Block(
                kind="list",
                provenance="system_suggested",
                items=[
                    f"{critic.get('citations_checked', 0)} citations re-resolved against the database",
                    f"{len(critic.get('citations_failed', []))} citations failed to resolve",
                    f"{critic.get('counter_examples_found', 0)} counter-examples found",
                    f"{len(critic.get('scripture_violations', []))} un-cited Arabic runs in the draft",
                ],
            )
        )

    from qra.agents.render import render

    rendered = render(session, run.output or "", strict=False)
    document.citations = rendered.citations
    for paragraph in [p for p in rendered.text.split("\n") if p.strip()]:
        if paragraph.startswith("#"):
            level = len(paragraph) - len(paragraph.lstrip("#"))
            document.add(Block(kind="heading", text=paragraph.lstrip("# "), level=max(2, level)))
        else:
            document.add(
                Block(kind="text", text=paragraph.lstrip("- "), language=language, rtl=rtl)
            )

    for item in ledger.get("disagreements", []):
        document.add(Block(kind="heading", text=f"{strings['disagreement']}: {item['topic']}", level=3))
        for position in item.get("positions", []):
            died = f" (d. {position['died_ah']} AH)" if position.get("died_ah") else ""
            document.add(
                Block(
                    kind="quote",
                    text=f"{position.get('author', '')}{died}: {position.get('excerpt', '')[:600]}",
                    language="ar",
                    rtl=True,
                    citation=position.get("citation"),
                )
            )
            if position.get("citation"):
                document.citations.append(position["citation"])

    if ledger.get("open_questions"):
        document.add(Block(kind="heading", text=strings["open_questions"], level=2))
        document.add(
            Block(kind="list", items=ledger["open_questions"], provenance="system_suggested")
        )

    _footer_blocks(document, session)
    return document


def from_hypothesis(session: Session, hypothesis_id: int, *, language: str | None = None) -> Document:
    """Render a hypothesis and its latest run — violations first, as everywhere."""
    row = session.get(Hypothesis, hypothesis_id)
    if row is None:
        raise ValueError(f"hypothesis {hypothesis_id} not found")
    language = language or row.language
    strings = _strings(language)
    latest = session.scalars(
        select(HypothesisRun)
        .where(HypothesisRun.hypothesis_id == row.id)
        .order_by(HypothesisRun.created_at.desc())
    ).first()

    document = Document(title=row.title, subtitle=row.statement, language=language)
    document.add(
        Block(kind="text", text=row.statement, language=language, rtl=language in ("ur", "ar"))
    )

    if latest is None:
        document.add(Block(kind="text", text="Not yet tested.", provenance="system_suggested"))
        _footer_blocks(document, session)
        return document

    statistics = latest.statistics or {}
    document.add(Block(kind="heading", text=strings["verdict"], level=2))
    document.add(Block(kind="text", text=latest.verdict.replace("_", " "), provenance="system_suggested"))
    document.add(
        Block(
            kind="stat",
            provenance="system_suggested",
            rows=[
                [strings["violations"], str(len(latest.violating))],
                [strings["supporting"], str(len(latest.supporting))],
                [strings["coverage"], f"{latest.coverage * 100:.1f}%"],
                [strings["baseline"], f"{float(statistics.get('baseline_rate', 0)) * 100:.1f}%"],
            ],
        )
    )
    if statistics.get("interpretation"):
        document.add(
            Block(kind="text", text=statistics["interpretation"], provenance="system_suggested")
        )
    if statistics.get("null_model"):
        document.add(
            Block(
                kind="text",
                text=f"Null model: {statistics['null_model']}",
                provenance="system_suggested",
            )
        )

    # Violations before support. The ordering is the product, not a preference.
    for label, ayah_ids in (
        (strings["violations"], latest.violating),
        (strings["supporting"], latest.supporting),
    ):
        document.add(Block(kind="heading", text=f"{label} ({len(ayah_ids)})", level=2))
        for span, citation in _ayah_blocks(session, ayah_ids[:40]):
            document.add(span)
            document.citations.append(citation)

    _footer_blocks(document, session)
    return document


def from_notes(session: Session, note_ids: list[int], *, language: str = "en", title: str = "Notes") -> Document:
    document = Document(title=title, language=language)
    for note_id in note_ids:
        note = session.get(Note, note_id)
        if note is None:
            continue
        document.add(Block(kind="heading", text=note.title, level=2))
        document.add(
            Block(
                kind="note",
                text=note.body,
                provenance=note.provenance,
                language=note.language,
                rtl=note.language in ("ur", "ar"),
            )
        )
        anchor_ids = [a.ayah_id for a in note.anchors if a.ayah_id]
        for span, citation in _ayah_blocks(session, anchor_ids):
            document.add(span)
            document.citations.append(citation)
    _footer_blocks(document, session)
    return document


def from_finding(session: Session, finding_id: int, *, language: str | None = None) -> Document:
    finding = session.get(Finding, finding_id)
    if finding is None:
        raise ValueError(f"finding {finding_id} not found")
    language = language or finding.language
    document = Document(title=finding.question, language=language)
    document.add(
        Block(
            kind="text",
            text=finding.summary,
            language=language,
            rtl=language in ("ur", "ar"),
            provenance="retrieved" if finding.review_status == "approved" else "system_suggested",
        )
    )
    if finding.review_status != "approved":
        document.add(
            Block(
                kind="text",
                text=f"Review status: {finding.review_status} — not signed off by a reviewer.",
                provenance="system_suggested",
            )
        )
    document.citations = list(finding.citations or [])
    _footer_blocks(document, session)
    return document


def _ayah_blocks(session: Session, ayah_ids: list[int]):
    """Ayah blocks rendered from the database — never from a caller's string."""
    from qra.citations import ayah_citation
    from qra.models import Ayah

    for ayah_id in ayah_ids:
        ayah = session.get(Ayah, ayah_id)
        if ayah is None:
            continue
        citation = ayah_citation(ayah).to_dict()
        yield (
            Block(
                kind="ayah",
                text=ayah.text_uthmani,
                ref=f"{ayah.surah_id}:{ayah.ayah_num}",
                language="ar",
                rtl=True,
                provenance="retrieved",
                citation=citation,
            ),
            citation,
        )
