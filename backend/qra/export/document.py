def _strings(language: str) -> dict:
    return STRINGS.get(language, STRINGS["en"])


def _footer_blocks(document: Document, session: Session) -> None:
    strings = _strings(document.language)
    labels = PROVENANCE_LABEL.get(document.language, PROVENANCE_LABEL["en"])
    document.add(Block(kind="heading", text=strings["provenance_key"], level=2))
    document.add(
        Block(
            kind="list",
            items=[
                f"{labels['retrieved']} — from a cited source in the corpus",
                f"{labels['system_suggested']} — computed or proposed by the system",
                f"{labels['own_note']} — written by the researcher",
            ],
            provenance="system_suggested",
        )
    )
    bibliography = document.bibliography()
    if bibliography.entries:
        document.add(Block(kind="heading", text=bibliography.labels["sources"], level=2))
        document.add(Block(kind="list", items=bibliography.lines(), provenance="retrieved"))
        document.licence = licence_notice(session, bibliography.entries, language=document.language)
    document.add(Block(kind="text", text=strings["no_generated_scripture"], provenance="system_suggested"))


